export interface LicenseGrantedInput {
  serial: string;
  kind: 'academic' | 'master';
  /** Who it is for, as the administrator wrote it. */
  grantedTo: string;
  /** "2 computers", "any number of computers". */
  seats: string;
  /** ISO, or null where it does not end. */
  expiresAt: string | null;
  accountUrl: string;
}

const sayDate = (iso: string): string =>
  new Date(iso).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric', timeZone: 'UTC' });

/** Sent when an administrator gives a licence. */
export const licenseGranted = (input: LicenseGrantedInput): RenderedEmail => {
  const what =
    input.kind === 'master'
      ? `A master licence for VC Composer. It covers ${input.seats} and does not expire.`
      : `An academic licence for VC Composer${input.grantedTo ? `, for ${input.grantedTo}` : ''}. It covers ${input.seats}${
          input.expiresAt ? ` until ${sayDate(input.expiresAt)}` : ' and does not expire'
        }.`;
  const how = `Sign in at ${siteHost()} with this email address (an emailed sign-in link is fine, no password is needed) to download VC Composer for Windows or macOS. It activates the first time you sign in on a computer.`;
  return {
    template: 'license_granted',
    version: 1,
    subject: input.kind === 'master' ? 'Your VC Composer master licence' : 'Your VC Composer academic licence',
    html: shell(
      input.kind === 'master' ? 'Your master licence' : 'Your academic licence',
      `<p style="margin:0 0 16px">${escapeHtml(what)}</p>
       ${serialBlock(input.serial)}
       ${primaryLink(input.accountUrl, 'Sign in and download')}
       ${note(escapeHtml(how))}`,
    ),
    text: [
      'VC COMPOSER',
      '',
      what,
      '',
      `Your licence: ${input.serial}`,
      '',
      `Sign in and download: ${input.accountUrl}`,
      '',
      how,
      '',
      siteHost(),
    ].join('\n'),
  };
};

export interface CollabInviteInput {
  /** As people typed them: escaped here. */
  projectName: string;
  inviterName: string;
  /** "Editor / composer", "Reviewer / director"... */
  roleLabel: string;
  acceptUrl: string;
}

/** An invitation to a shared project. */
export const collabInvite = (input: CollabInviteInput): RenderedEmail => {
  const who = input.inviterName.trim() || 'A VC Composer user';
  return {
    template: 'collab_invite',
    version: 1,
    subject: `${who} invited you to "${input.projectName}" in VC Composer`,
    html: shell(
      'You are invited to a shared project',
      `<p style="margin:0 0 16px">${escapeHtml(who)} invited you to <strong>${escapeHtml(input.projectName)}</strong> as
       ${escapeHtml(input.roleLabel)}.</p>
       ${primaryLink(input.acceptUrl, 'Accept the invitation')}
       ${note('Sign in or create a free account to accept. Reviewers and viewers need no subscription; editors are covered by the project owner’s plan.')}`,
    ),
    text: [
      'VC COMPOSER',
      '',
      `${who} invited you to "${input.projectName}" as ${input.roleLabel}.`,
      '',
      `Accept: ${input.acceptUrl}`,
      '',
      'Sign in or create a free account to accept. Reviewers and viewers need no subscription; editors are covered by the project owner’s plan.',
      '',
      siteHost(),
    ].join('\n'),
  };
};
