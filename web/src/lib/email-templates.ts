import { PLATFORM_LABEL, type Platform } from '@/domain';
import { env } from './env';
import { COMPANY_NAME, SITE_NAME } from './site';

/**
 * Transactional email templates.
 *
 * They live in their own module with an explicit version on each, so a change
 * to what customers receive is a visible, reviewable diff, and the version
 * that sent any given message is recorded in `email_events` as
 * `template@version`. **Bump the version whenever the words or the look
 * change.**
 *
 * The look follows the app's own palette within what email clients allow:
 * tables for layout, every style inline, solid colours, no web fonts and no
 * images (the header is a text wordmark, so a client that blocks images still
 * shows it).
 */

export interface RenderedEmail {
  subject: string;
  html: string;
  text: string;
  template: string;
  version: number;
}

// The app's palette, as literals because email has no CSS variables.
const BACKGROUND = '#1e2126';
const PANEL = '#262a31';
const BORDER = '#363b44';
const TEXT = '#e6e8eb';
const MUTED = '#9aa1ab';
const ACCENT = '#4f9de8';
const WARM = '#e8a33d';

const FONT = "system-ui, -apple-system, 'Segoe UI', Helvetica, Arial, sans-serif";
const MONO = "ui-monospace, 'SF Mono', Menlo, Consolas, monospace";

/** The site's host, for the footer line: whatever NEXT_PUBLIC_SITE_URL says. */
const siteHost = (): string => new URL(env.siteUrl).host;

/**
 * Text that came from a person (an administrator's "granted to" note), going
 * into HTML. Everything else interpolated here is generated by this codebase.
 */
const escapeHtml = (text: string): string =>
  text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** The outer document: a dark card on a dark page, so a client's dark mode changes nothing. */
const shell = (title: string, body: string): string => `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="color-scheme" content="dark">
  <meta name="supported-color-schemes" content="dark">
  <title>${title}</title>
</head>
<body style="margin:0;padding:0;background:${BACKGROUND}">
  <table role="presentation" cellpadding="0" cellspacing="0" border="0" width="100%" style="background:${BACKGROUND}">
    <tr>
      <td align="center" style="padding:32px 16px">
        <table role="presentation" cellpadding="0" cellspacing="0" border="0" width="560" style="max-width:560px;width:100%">
          <tr>
            <td style="padding:4px 0 18px;font-family:${FONT};font-size:15px;font-weight:700;letter-spacing:0.08em;color:${TEXT}">
              VC COMPOSER
            </td>
          </tr>
          <tr>
            <td style="background:${PANEL};border:1px solid ${BORDER};border-top:3px solid ${ACCENT};border-radius:6px;padding:32px 32px 28px">
              <h1 style="margin:0 0 20px;font-family:${FONT};font-size:22px;font-weight:600;line-height:1.3;color:${TEXT}">${title}</h1>
              <div style="font-family:${FONT};font-size:16px;line-height:1.6;color:${TEXT}">
                ${body}
              </div>
            </td>
          </tr>
          <tr>
            <td align="center" style="padding:22px 12px 8px">
              <p style="margin:0;font-family:${FONT};font-size:12px;line-height:1.6;color:${MUTED}">
                ${SITE_NAME} &middot; Windows and macOS &middot; a ${COMPANY_NAME} product<br>
                <a href="${env.siteUrl}" style="color:${ACCENT};text-decoration:none">${siteHost()}</a>
              </p>
            </td>
          </tr>
        </table>
      </td>
    </tr>
  </table>
</body>
</html>`;

/** The serial, framed so it can be read off the screen and typed. */
const serialBlock = (serial: string): string => `
  <table role="presentation" cellpadding="0" cellspacing="0" border="0" width="100%" style="margin:22px 0">
    <tr>
      <td align="center" style="background:${BACKGROUND};border:1px solid ${BORDER};border-radius:4px;padding:18px 16px">
        <span style="font-family:${FONT};font-size:11px;font-weight:600;letter-spacing:0.16em;text-transform:uppercase;color:${MUTED}">Your licence</span><br>
        <span style="display:inline-block;margin-top:8px;font-family:${MONO};font-size:20px;font-weight:600;letter-spacing:0.06em;color:${WARM}">${serial}</span>
      </td>
    </tr>
  </table>`;

/** A button: a table cell with a background, which every client draws. */
const primaryLink = (url: string, label: string): string => `
  <table role="presentation" cellpadding="0" cellspacing="0" border="0" style="margin:8px 0 20px">
    <tr>
      <td style="background:${ACCENT};border-radius:4px">
        <a href="${url}" style="display:inline-block;padding:12px 24px;font-family:${FONT};font-size:14px;font-weight:600;color:#0d1117;text-decoration:none">${label}</a>
      </td>
    </tr>
  </table>`;

const note = (text: string): string =>
  `<p style="margin:0;font-family:${FONT};font-size:14px;line-height:1.6;color:${MUTED}">${text}</p>`;

export interface PurchaseEmailInput {
  serial: string;
  platform: Platform | null;
  accountUrl: string;
}

/** Sent once, when a subscription's licence is first issued. */
export const purchaseConfirmation = (input: PurchaseEmailInput): RenderedEmail => {
  const ready = input.platform
    ? `Your download for ${PLATFORM_LABEL[input.platform]} is ready.`
    : 'Your downloads for Windows and macOS are ready.';

  return {
    template: 'purchase_confirmation',
    version: 1,
    subject: 'Your VC Composer licence and download',
    html: shell(
      'Thank you for subscribing to VC Composer',
      `<p style="margin:0 0 8px">${ready}</p>
       ${serialBlock(input.serial)}
       ${primaryLink(input.accountUrl, 'Go to your downloads')}
       ${note('Your licence covers both Windows and macOS. Sign in to your account at any time to download the current build, see the computers it is activated on, or manage your subscription.')}`,
    ),
    text: [
      'VC COMPOSER',
      '',
      'Thank you for subscribing to VC Composer.',
      '',
      ready,
      '',
      `Your licence: ${input.serial}`,
      '',
      `Downloads: ${input.accountUrl}`,
      '',
      'Your licence covers both Windows and macOS. Sign in to your account at any time to download the current build, see the computers it is activated on, or manage your subscription.',
      '',
      siteHost(),
    ].join('\n'),
  };
};

